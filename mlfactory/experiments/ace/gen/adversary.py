"""Bounded counterexample search: shortest command sequence driving a
credit counter negative.

Reasoning-shaped adversarial verification (generalizes adversarial_testing).
The search space is a small explicit graph (modes x credits), so the task is
bounded BFS-like exploration — but the shortest witness has a TARGET depth,
so greedy one-step lookahead fails. Generated by sampling rule tables and
keeping instances whose shortest witness has exactly the target depth.

Knobs:
    n_modes       3-4   controller modes
    target_depth  4-6   required shortest-witness length
    max_witness   1-3   cap on number of shortest witnesses
"""
from __future__ import annotations

import random
import re
from collections import deque

from .common import Problem, answer_text

ALPHABET = "ABC"
DELTAS = [-2, -1, -1, 0, 1, 1, 2]


def _bfs(rules, n_modes, maxd=9, clamp=14):
    """Shortest sequences from (M0, c=0) to c<0.
    Returns (depth, witnesses[list of (seq, credit_trace)]) or (None, [])."""
    start = (0, 0)
    depth_of = {start: 0}
    parent = {start: None}
    witnesses = []
    wdepth = None
    dq = deque([start])
    while dq:
        m, c = dq.popleft()
        d = depth_of[(m, c)]
        if wdepth is not None and d >= wdepth:
            continue
        if d >= maxd:
            continue
        for cmd in ALPHABET:
            nm, dn = rules[(m, cmd)]
            nc = c + dn
            if nc < 0:
                if wdepth is None or d + 1 == wdepth:
                    wdepth = d + 1
                    witnesses.append(((m, c), cmd))
                continue
            if nc > clamp:
                continue
            if (nm, nc) not in depth_of:
                depth_of[(nm, nc)] = d + 1
                parent[(nm, nc)] = ((m, c), cmd)
                dq.append((nm, nc))
    if wdepth is None:
        return None, []
    # reconstruct first witness
    seq, trace = [], []
    state, cmd = witnesses[0]
    path = [cmd]
    c = state[1] + rules[(state[0], cmd)][1]
    trace.append(c)
    while state in parent and parent[state] is not None:
        state, cmd = parent[state]
        path.append(cmd)
    path.reverse()
    # recompute full trace cleanly
    m, c = 0, 0
    trace = []
    for cmd in path:
        m, dn = rules[(m, cmd)]
        c += dn
        trace.append(c)
    return wdepth, [("".join(path), trace)] * len(witnesses)


def make(rng: random.Random, knobs: dict) -> Problem:
    k, target = knobs["n_modes"], knobs["target_depth"]
    max_wit = knobs.get("max_witness", 3)

    for _attempt in range(600):
        rules = {}
        for m in range(k):
            for cmd in ALPHABET:
                rules[(m, cmd)] = (rng.randrange(k), rng.choice(DELTAS))
        depth, wits = _bfs(rules, k)
        if depth != target or not (1 <= len(wits) <= max_wit):
            continue
        seq, trace = wits[0]

        mode_lines = []
        for m in range(k):
            parts = "; ".join(
                f"{cmd} -> M{rules[(m, cmd)][0]}, c "
                f"{'+' if rules[(m, cmd)][1] >= 0 else '-'}"
                f" {abs(rules[(m, cmd)][1])}"
                for cmd in ALPHABET)
            mode_lines.append(f"  M{m}: {parts}")
        prose = (
            f"A credit-based flow controller has modes M0 through M{k-1} and "
            "one integer credit counter c. It starts in mode M0 with c = 0. "
            "It consumes a command sequence over {A, B, C}, one command at a "
            "time; each step applies the rule for its current mode and that "
            "command, setting the next mode and adjusting c.\n\n"
            "Rules:\n" + "\n".join(mode_lines) +
            "\n\nA vendor claims c can never go negative."
        )
        ans = f"{seq}: {','.join(str(x) for x in trace)}"
        return Problem(
            family="adversary", prose=prose,
            question=f"Give a shortest command sequence that drives c "
                     f"negative, and the credit value after each step "
                     f"(format: CMDS: c1,c2,...). The shortest such sequence "
                     f"has length {target}.",
            answer=ans,
            verifier_kind="counterexample_checker",
            objective_task="adversarial_verification",
            search_topology="deceptive_local_optimum",
            knobs={"n_modes": k, "target_depth": target,
                   "n_witnesses": len(wits),
                   "rules": sorted([[m, cmd, nm, dn]
                                    for (m, cmd), (nm, dn) in rules.items()])},
            seed=rng.randrange(2**31))
    raise RuntimeError("adversary: no instance at target depth found")


# Tolerant witness extraction: the command sequence may be contiguous
# ("BAAB") or separated ("B A A B", "B,A,A,B"), and the credit trace may be
# decorated (":", "cmds:", "credits:", backticks, parens). Label words are
# stripped first so a label starting with a command letter ("CMDS") cannot
# leak into the sequence. Semantics unchanged: the witness must be SHORTEST
# (same length as the reference) and must drive the counter negative under the
# rule table; a stated trace must match the re-derived trace exactly.
def _witness(ans: str):
    t = re.sub(r"\s+", " ", ans.strip())
    t = re.sub(r"(?i)\b(cmds?|commands?|credits?|credit|sequence|seq|trace|values?|result|answer)\b",
               " ", t)
    m = re.search(r"[ABC](?:[\s,]*[ABC])*", t)
    if not m:
        return None, []
    seq = re.sub(r"[^ABC]", "", m.group(0))
    tr = [int(x) for x in re.findall(r"-?\d+", t[m.end():])]
    return (seq or None), tr


def check(completion: str, reference: str, knobs: dict | None = None) -> bool:
    g_seq, g_tr = _witness(answer_text(completion))
    w_seq, w_tr = _witness(answer_text(reference))
    if not g_seq or not w_seq:
        return False
    # shortest witness required: same length as the reference witness
    if len(g_seq) != len(w_seq):
        return False
    # verify against the rule table when available (authoritative)
    if knobs and "rules" in knobs:
        rules = {(m, cmd): (nm, dn) for m, cmd, nm, dn in knobs["rules"]}
        m, c = 0, 0
        derived = []
        for cmd in g_seq:
            if (m, cmd) not in rules:
                return False
            m, dn = rules[(m, cmd)]
            c += dn
            derived.append(c)
        if c >= 0:
            return False
        # full answer required: a stated credit trace must be present and
        # match the re-derived trace exactly (the prompt asks for both the
        # sequence and the credit values)
        return bool(g_tr) and g_tr == derived
    # no rules: exact match only
    return g_seq == w_seq and g_tr == w_tr
